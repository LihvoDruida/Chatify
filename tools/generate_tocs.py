#!/usr/bin/env python3
"""Generate every flavor TOC from Chatify.toc, including Forever and legacy Wrath.

The generic TOC lists all packaged interface targets for client fallback. Flavor
TOCs select their own interface, identity and support tier. Runtime routing still
probes APIs; TOC metadata is not a capability detector.

    python3 tools/generate_tocs.py
    python3 tools/generate_tocs.py --check
    python3 tools/generate_tocs.py --check --ignore-version  # pre-tag CI
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Chatify.toc"
# Suffix -> interface list, flavor, expansion, display name, support tier.
FLAVOURS = {
    "Vanilla": ("11509, 11508", "classic", "Vanilla", "Classic Era / Hardcore / Season of Discovery", "current"),
    "TBC": ("20506", "classic", "TBC", "Burning Crusade Classic Anniversary", "current"),
    "Wrath": ("38002, 30405", "classic", "Wrath", "Titan Reforged / Wrath Classic", "current / legacy"),
    "WrathLegacy": ("30405", "classic-legacy", "Wrath", "Wrath Classic 3.4.5", "legacy"),
    "Cata": ("40402", "classic-legacy", "Cata", "Cataclysm Classic", "legacy"),
    "Mists": ("50504", "classic", "Mists", "Mists of Pandaria Classic", "current"),
    "Camelot": ("16001", "forever", "Forever", "World of Warcraft: Forever", "beta"),
}
HEADERS = ("Interface", "X-Flavor", "X-Expansion", "X-Chatify-Client", "X-Chatify-Support-Tier")


def build(lines, target, suffix):
    replacements = dict(zip(HEADERS, target))
    out = []
    for line in lines:
        if line == "Forever.lua":
            continue
        if line.startswith("## ") and ":" in line:
            key = line[3:].split(":", 1)[0]
            if key in replacements:
                line = f"## {key}: {replacements[key]}"
        out.append(line)
        if suffix == "Camelot" and line == "Compatibility.lua":
            out.append("Forever.lua")
    missing = [key for key in HEADERS if not any(line.startswith(f"## {key}:") for line in out)]
    if missing:
        sys.exit("Chatify.toc is missing required headers: " + ", ".join(missing))
    # Keep the first directive first, even on strict TOC parsers.
    out.insert(1, "# GENERATED by tools/generate_tocs.py; edit Chatify.toc instead.")
    return "\n".join(out).rstrip() + "\n"


def normalize_version_metadata(content):
    # Versions are filled from the triggering tag during packaging; all other
    # source TOC metadata still needs to match the generated flavor files.
    return "\n".join(
        "## Version: <tag>" if line.startswith("## Version:") else line
        for line in content.split("\n")
    )


def main():
    check = "--check" in sys.argv
    ignore_version = "--ignore-version" in sys.argv
    if ignore_version and not check:
        sys.exit("--ignore-version may only be used together with --check")
    lines = SOURCE.read_text(encoding="utf-8-sig").splitlines()
    if not lines or not lines[0].startswith("## Interface:"):
        sys.exit("Chatify.toc must begin with ## Interface.")
    packaged_interfaces = {value.strip() for value in lines[0].split(":", 1)[1].split(",")}
    stale = []
    for suffix, target in FLAVOURS.items():
        if not set(target[0].split(", ")).issubset(packaged_interfaces):
            sys.exit(f"Generic TOC is missing interfaces from {suffix}.")
        path = ROOT / f"Chatify_{suffix}.toc"
        content = build(lines, target, suffix)
        if check:
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if ignore_version:
                valid = normalize_version_metadata(actual) == normalize_version_metadata(content)
            else:
                valid = actual == content
            if not valid:
                stale.append(path.name)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.name} (Interface {target[0]})")
    if check:
        if stale:
            sys.exit("Out of date, re-run tools/generate_tocs.py: " + ", ".join(stale))
        print("All seven flavor TOCs are current, including Forever and legacy Wrath."
              + (" Local release versions ignored until tag sync." if ignore_version else ""))


if __name__ == "__main__":
    main()
